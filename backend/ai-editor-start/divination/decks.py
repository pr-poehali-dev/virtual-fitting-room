"""Колоды карт. Новая колода = новая запись в DECKS."""

# 36 карт Ленорман в каноническом порядке (номер = традиционный номер карты).
LENORMAND_CARDS = [
    'Всадник', 'Клевер', 'Корабль', 'Дом', 'Дерево', 'Тучи', 'Змея', 'Гроб',
    'Букет', 'Коса', 'Метла', 'Птицы', 'Ребёнок', 'Лиса', 'Медведь', 'Звёзды',
    'Аист', 'Собака', 'Башня', 'Сад', 'Гора', 'Развилка', 'Крысы', 'Сердце',
    'Кольцо', 'Книга', 'Письмо', 'Мужчина', 'Женщина', 'Лилии', 'Солнце', 'Луна',
    'Ключ', 'Рыбы', 'Якорь', 'Крест',
]

# Старшие арканы Таро
TAROT_MAJOR = [
    'Шут', 'Маг', 'Верховная Жрица', 'Императрица', 'Император', 'Иерофант',
    'Влюблённые', 'Колесница', 'Сила', 'Отшельник', 'Колесо Фортуны',
    'Справедливость', 'Повешенный', 'Смерть', 'Умеренность', 'Дьявол',
    'Башня', 'Звезда', 'Луна', 'Солнце', 'Суд', 'Мир',
]

_SUITS = [
    ('Жезлов', 'Жезлы'),
    ('Кубков', 'Кубки'),
    ('Мечей', 'Мечи'),
    ('Пентаклей', 'Пентакли'),
]
_RANKS = [
    'Туз', 'Двойка', 'Тройка', 'Четвёрка', 'Пятёрка', 'Шестёрка',
    'Семёрка', 'Восьмёрка', 'Девятка', 'Десятка',
    'Паж', 'Рыцарь', 'Королева', 'Король',
]


def _build_tarot_minor():
    cards = []
    for suit_genitive, _ in _SUITS:
        for rank in _RANKS:
            cards.append(f'{rank} {suit_genitive}')
    return cards


TAROT_MINOR = _build_tarot_minor()
TAROT_CARDS = TAROT_MAJOR + TAROT_MINOR

DECKS = {
    'lenormand': {
        'title': 'Ленорман',
        'cards': LENORMAND_CARDS,
        # У Ленорман позиции расклада традиционно называются «домами»
        'position_word': 'дом',
        'house_names': LENORMAND_CARDS,
    },
    'tarot': {
        'title': 'Таро',
        'cards': TAROT_CARDS,
        'position_word': 'позиция',
        'house_names': None,
    },
}


def get_deck(deck_id: str) -> dict:
    return DECKS.get(deck_id) or DECKS['lenormand']
