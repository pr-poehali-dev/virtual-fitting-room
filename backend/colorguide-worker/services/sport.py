def build_week_block() -> str:
    lines = ['ТЕМЫ ДНЕЙ НЕДЕЛИ — акцент тренировок каждого дня:']
    for day, planet, system, ideas in WEEK_THEMES:
        lines.append(f'- {day.upper()} ({planet}) — {system}. Подходящие занятия: {ideas}.')
    return '\n'.join(lines) + '\n\n' + WEEK_RULES


def build_params_block(form_params: dict) -> str:
    return make_params_block(form_params, SPORT_FIELDS, 'СПОРТ') + '\n\n' + build_week_block()


