WEEK_ORDER = ['Понедельник', 'Вторник', 'Среда', 'Четверг', 'Пятница', 'Суббота', 'Воскресенье']


def build_days_block() -> str:
    lines = ['АРОМАТЫ, ТРАВЫ И СРЕДСТВА ПО ДНЯМ НЕДЕЛИ — основа ритуалов.']
    for day in WEEK_ORDER:
        d = DAYS[day]
        lines.append(f'{day.upper()}: ароматы — {d["aromas"]}. Травы и цветы — {d["herbs"]}. Масла и мёд — {d["care"]}.')
    lines.append('''
КАК ИСПОЛЬЗОВАТЬ:
- Ритуалы каждого дня строй в первую очередь на ароматах, травах и маслах ЭТОГО дня: аромалампа, ванна, массаж, маска, скраб, ополаскиватель, компресс, травяной чай во время ритуала. Ежедневный утренний и вечерний уход — базовый, по анкете.
- В пятницу предложи зажечь оранжевую свечу во время ритуала.
- Анкета клиента важнее списка: аллергены и всё, что клиенту не подходит, не используй никогда.
- БЕЗОПАСНОСТЬ (коротко упомяни в ритуалах с маслами и в "safety"): эфирные масла — только разбавленными в базовом масле (несколько капель на столовую ложку), сначала тест на сгибе локтя; после цитрусовых масел (лимон, бергамот, лайм, лиметт) — не выходить на солнце несколько часов; благовония и смолы — только в проветриваемой комнате; при беременности, астме и для детей — только после консультации с врачом.''')
    return '\n'.join(lines)
