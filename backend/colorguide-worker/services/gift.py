def build_params_block(form_params: dict) -> str:
    """Собирает текстовый блок ТОЛЬКО из заполненных параметров анкеты."""
    if not form_params or not isinstance(form_params, dict):
        return ''

    lines = []

    def add(label, value):
        if value is None:
            return
        if isinstance(value, (list, tuple)):
            vals = [str(v).strip() for v in value if v not in (None, '')]
            if not vals:
                return
            lines.append(f'- {label}: {", ".join(vals)}')
        else:
            s = str(value).strip()
            if s:
                lines.append(f'- {label}: {s}')

    add('Пол получателя', form_params.get('recipient_gender'))
    add('Возраст получателя', form_params.get('recipient_age'))
    add('Кем приходится дарителю', form_params.get('relation'))
    add('Повод для подарка', form_params.get('occasion'))
    add('Бюджет, от (руб.)', form_params.get('budget_min'))
    add('Бюджет, до (руб.)', form_params.get('budget_max'))
    add('Знак зодиака получателя', form_params.get('zodiac'))
    add('Архетип(ы) получателя по Карлу Юнгу', form_params.get('archetypes'))
    add('Цветотип внешности получателя', form_params.get('colortypes'))
    add('Интересы и увлечения получателя', form_params.get('interests'))
    add('Предпочтительный формат подарка', form_params.get('gift_formats'))
    add('Сезон / время года', form_params.get('season'))
    add('Желаемое настроение подарка (теги)', form_params.get('tags'))
    add('Что уже дарили раньше (НЕ повторяй эти подарки)', form_params.get('already_gifted'))
    add('Ограничения и стоп-темы (строго избегай)', form_params.get('restrictions'))
    add('Комментарий от дарителя', form_params.get('comment'))

    if not lines:
        return ''
    return (
        'АНКЕТА ОТ ДАРИТЕЛЯ (учитывай все указанные ниже параметры, '
        'не указанные — не выдумывай):\n' + '\n'.join(lines)
    )


