def build_params_block(form_params: dict) -> str:
    """Собирает текстовый блок ТОЛЬКО из заполненных параметров анкеты."""
    if not form_params or not isinstance(form_params, dict):
        return ''

    lines = []

    def add(label, value):
        if value is None:
            return
        if isinstance(value, (list, tuple)):
            vals = [str(v).strip() for v in value if v not in (None, '')]
            if not vals:
                return
            lines.append(f'- {label}: {", ".join(vals)}')
        else:
            s = str(value).strip()
            if s:
                lines.append(f'- {label}: {s}')

    add('Пол', form_params.get('gender'))
    add('Возраст', form_params.get('age'))
    add('Повод / когда носить', form_params.get('occasion'))
    add('Сезон', form_params.get('season'))
    add('Время суток', form_params.get('time_of_day'))
    add('Знак зодиака', form_params.get('zodiac'))
    add('Архетип(ы) по Карлу Юнгу', form_params.get('archetypes'))
    add('Цветотип внешности', form_params.get('colortypes'))
    add('Типаж по Дэвиду Кибби', form_params.get('kibbe'))
    add('Ноты, которые НРАВЯТСЯ (обязательно используй их)', form_params.get('favorite_notes'))
    add('Ноты, которые НЕ НРАВЯТСЯ (строго исключи их)', form_params.get('disliked_notes'))
    add('Желаемая стойкость', form_params.get('longevity'))
    add('Желаемый шлейф (сколько места занимает аромат)', form_params.get('sillage'))
    add('Тип парфюмерии', form_params.get('perfume_types'))
    add('Ароматы, которые нравились раньше', form_params.get('loved_perfumes'))
    add('Бюджет, от (руб.)', form_params.get('budget_min'))
    add('Бюджет, до (руб.)', form_params.get('budget_max'))
    add('Чувствительность к запахам', form_params.get('sensitivity'))
    add('Желаемое настроение аромата (теги)', form_params.get('tags'))
    add('Комментарий клиента', form_params.get('comment'))

    if not lines:
        return ''
    return (
        'ПАРАМЕТРЫ ОТ КЛИЕНТА (учитывай все указанные ниже, '
        'не указанные — не выдумывай):\n' + '\n'.join(lines)
    )


