def build_photo_block(has_person: bool, ref_count: int) -> str:
    """Пояснение модели, где чьё фото. Пустая строка, если фото не приложены."""
    if not has_person and ref_count == 0:
        return (
            'ФОТО НЕ ПРИЛОЖЕНЫ. Отвечай только по тексту вопроса. '
            'Не выдумывай внешность, вещи или детали, которых нет в вопросе, '
            'и не делай вид, что видишь изображение.'
        )

    lines = ['ПРИЛОЖЕННЫЕ ИЗОБРАЖЕНИЯ (в порядке передачи):']
    idx = 1
    if has_person:
        lines.append(
            f'{idx}) ФОТО АВТОРА ВОПРОСА — это сам человек, который к тебе обратился. '
            'Его внешность, фигуру, колорит и стиль анализируй и советы давай ДЛЯ НЕГО.'
        )
        idx += 1
    for i in range(ref_count):
        lines.append(
            f'{idx}) РЕФЕРЕНС {i + 1} — изображение, о котором спрашивает автор '
            '(вещь, образ или что угодно иное). Это НЕ автор вопроса: '
            'запрещено принимать человека с референса за автора и давать советы ему.'
        )
        idx += 1
    lines.append(
        'Строго не путай роли изображений. Если чего-то на фото не видно — '
        'честно скажи об этом, но не выдумывай.'
    )
    return '\n'.join(lines)


def build_request_block(form_params: dict) -> str:
    """Собирает блок с вопросом пользователя и пожеланиями по промпту."""
    if not isinstance(form_params, dict):
        form_params = {}

    question = str(form_params.get('question') or '').strip()
    want_prompt = bool(form_params.get('want_prompt'))
    purpose = str(form_params.get('prompt_purpose') or '').strip()

    lines = ['ВОПРОС АВТОРА (отвечай именно на него, ничего не подменяя):', question or '—']

    if want_prompt:
        lines.append('')
        lines.append(
            'АВТОР ПОПРОСИЛ ГОТОВЫЙ ПРОМПТ для генерации изображения. '
            'Обязательно заполни поле "image_prompt".'
        )
        if purpose:
            lines.append(f'Промпт нужен для: {purpose}')
    else:
        lines.append('')
        lines.append(
            'Промпт для генерации автор НЕ запрашивал: поле "image_prompt" оставь пустой строкой.'
        )

    return '\n'.join(lines)


