export const getPageSeo = (pathname: string): PageSeo => {
  const exact = PAGE_SEO[pathname];
  if (exact) return exact;
  const section = SECTION_SEO.find((s) => pathname.startsWith(s.prefix));
  if (section) return section.seo;
  return DEFAULT_SEO;
};